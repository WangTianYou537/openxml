/// Look up a namespace URI by its conventional prefix.
pub fn uri_for_prefix(prefix: &str) -> Option<&'static str> {
    NAMESPACES.iter().find(|n| n.prefix == prefix).map(|n| n.uri)
}

/// Look up the conventional prefix for a namespace URI.
pub fn prefix_for_uri(uri: &str) -> Option<&'static str> {
    NAMESPACES.iter().find(|n| n.uri == uri).map(|n| n.prefix)
}

/// Look up the introduction version for a namespace prefix.
pub fn version_for_prefix(prefix: &str) -> Option<FileFormatVersions> {
    NAMESPACES.iter().find(|n| n.prefix == prefix).and_then(|n| n.version)
}

